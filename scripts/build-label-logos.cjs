/**
 * Builds src/server/labels/logos.generated.ts from public/brand: the Vishwaship logo and each courier logo,
 * resized for labels, in colour (A4) and pure black & white (thermal printers — high contrast, no dithering).
 * Run after changing a logo: node scripts/build-label-logos.cjs
 */
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

async function variant(file, width) {
  const trimmed = await sharp(file).flatten({ background: "#ffffff" }).trim({ threshold: 12 }).toBuffer();
  const base = sharp(trimmed).resize({ width, withoutEnlargement: true });
  const color = await base.clone().png({ compressionLevel: 9, palette: true, colors: 64 }).toBuffer();
  // light orange and navy both become solid black; the background stays white
  const mono = await base.clone().grayscale().threshold(200).png({ compressionLevel: 9, palette: true, colors: 2 }).toBuffer();
  const meta = await sharp(color).metadata();
  return { color: color.toString("base64"), mono: mono.toString("base64"), w: meta.width, h: meta.height };
}

(async () => {
  const out = { vishwaship: await variant("public/brand/vishwaship-logo-transparent.png", 640) };
  const carriers = {};
  for (const f of fs.readdirSync("public/brand/carriers").filter((x) => x.endsWith(".png"))) carriers[path.basename(f, ".png")] = await variant(path.join("public/brand/carriers", f), 420);
  const body = `// GENERATED by scripts/build-label-logos.cjs — do not edit.\n/* eslint-disable */\nexport type LabelLogo = { color: string; mono: string; w: number; h: number };\nexport const VISHWASHIP_LOGO: LabelLogo = ${JSON.stringify(out.vishwaship)};\nexport const CARRIER_LOGOS: Record<string, LabelLogo> = ${JSON.stringify(carriers)};\n`;
  fs.writeFileSync("src/server/labels/logos.generated.ts", body);
  console.log("logos:", Object.keys(carriers).length + 1, "size:", Math.round(body.length / 1024), "KB");
})();
