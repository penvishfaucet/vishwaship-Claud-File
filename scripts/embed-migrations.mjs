/**
 * Copies migrations/*.sql + meta/_journal.json into src/server/db/migrations.generated.ts so the app can
 * migrate the database on start even when the host ships only the build output (Hostinger Web Apps do not
 * deploy the /migrations folder). Runs automatically before `npm run build` (prebuild).
 * Output shape matches drizzle's readMigrationFiles(); content is normalised to LF so the file is stable.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const dir = "migrations";
const journal = JSON.parse(readFileSync(`${dir}/meta/_journal.json`, "utf8"));
const migrations = journal.entries.map((e) => {
  const query = readFileSync(`${dir}/${e.tag}.sql`, "utf8").replace(/\r\n/g, "\n");
  return { tag: e.tag, sql: query.split("--> statement-breakpoint"), bps: e.breakpoints, folderMillis: e.when, hash: createHash("sha256").update(query).digest("hex") };
});

const out = `// GENERATED by scripts/embed-migrations.mjs from /migrations — do not edit. Regenerated on every build.
export type EmbeddedMigration = { tag: string; sql: string[]; bps: boolean; folderMillis: number; hash: string };
export const EMBEDDED_MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(migrations, null, 1)};
`;
writeFileSync("src/server/db/migrations.generated.ts", out);
console.log(`[embed-migrations] ${migrations.length} migrations embedded`);
